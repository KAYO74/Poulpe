const dictionaries: Record<Lang, Record<MessageKey, string>> = { fr, en };

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('poulpe.lang');
    if (saved === 'fr' || saved === 'en') return saved;
  } catch {
    /* stockage indisponible */
  }
  return typeof navigator !== 'undefined' && navigator.language?.startsWith('fr') ? 'fr' : 'en';
}

let lang: Lang = initialLang();
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return lang;
}

export function setLang(next: Lang): void {
  lang = next;
  try {
    localStorage.setItem('poulpe.lang', next);
  } catch {
    /* stockage indisponible */
  }
  document.documentElement.lang = next;
  listeners.forEach((l) => l());
}

export function t(key: MessageKey | string, vars?: Record<string, string | number>): string {
  let s = (dictionaries[lang] as Record<string, string>)[key] ?? (fr as Record<string, string>)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Re-rend le composant quand la langue change. */
export function useT(): typeof t {
  useSyncExternalStore(
    (cb) => {
      listeners.add(cb);
      return () => listeners.delete(cb);
    },
    () => lang,
  );
  return t;
}
